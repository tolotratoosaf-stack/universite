-- ===============================================
--      CREATION DU TABLE ETUDIANT
-- ===============================================
CREATE TABLE etudiant (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  -- information de l'etudiant
  matricule CHAR(14) NOT NULL UNIQUE,
  nom VARCHAR(200) NOT NULL,
  prenom VARCHAR(255) NOT NULL,
  sexe TINYINT (1) NOT NULL,
  date_naissance DATE NOT NULL,
  lieu_naissance VARCHAR(255),
  telephone VARCHAR(20) NOT NULL,
  email VARCHAR(255),
  residence VARCHAR(255),
  -- 
  -- information parents
  --   MERE
  mere_nom VARCHAR(255),
  mere_prenom VARCHAR(255),
  mere_contact VARCHAR(255),
  --   PERE
  pere_nom VARCHAR(255),
  pere_prenom VARCHAR(255),
  pere_contact VARCHAR(255),
  --   TUTEUR
  tuteur_nom VARCHAR(255),
  tuteur_prenom VARCHAR(255),
  tuteur_contact VARCHAR(255),
  tuteur_lien VARCHAR(255),
  --   
  --   INDEXATION
  INDEX idx_nom_prenom (nom, prenom)
);

